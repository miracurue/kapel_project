'use strict';

/**
 * «Карманный психолог» — простой детерминированный сценарий на ключевых
 * словах: поддерживающие реплики + обязательное направление к врачу при
 * признаках кризиса. Это не диагностика и не замена терапии — бот никогда
 * не выставляет диагноз, только поддерживает и эскалирует.
 * Финальные формулировки должен передать ClinicalLead (RES-2).
 */

const CRISIS_KEYWORDS = [
  'покончить с собой', 'суицид', 'не хочу жить', 'убить себя',
  'причинить себе вред', 'самоповреждение', 'незачем жить',
];

const SADNESS_KEYWORDS = ['грустно', 'плохо', 'тяжело', 'депресс', 'одиноко', 'тревож', 'страшно', 'паника'];
const SLEEP_KEYWORDS = ['не сплю', 'бессонница', 'не могу уснуть', 'сон'];
const GREETING_KEYWORDS = ['привет', 'здравствуй', 'добрый день', 'добрый вечер'];

function detectIntent(text) {
  const t = text.toLowerCase();
  if (CRISIS_KEYWORDS.some((k) => t.includes(k))) return 'crisis';
  if (SLEEP_KEYWORDS.some((k) => t.includes(k))) return 'sleep';
  if (SADNESS_KEYWORDS.some((k) => t.includes(k))) return 'sadness';
  if (GREETING_KEYWORDS.some((k) => t.includes(k))) return 'greeting';
  return 'default';
}

const RESPONSES = {
  crisis: 'Мне важно, что вы это сказали. Похоже, вам сейчас очень тяжело, и это серьёзно — я не могу заменить врача в такой ситуации. '
    + 'Пожалуйста, свяжитесь с вашим врачом как можно скорее; я уже отметил это как повод для срочного внимания специалиста. '
    + 'Если есть риск для жизни прямо сейчас — наберите экстренные службы (112) или телефон доверия.',
  sleep: 'Проблемы со сном часто идут рядом с тревогой и подавленным настроением. Попробуйте отметить это в дневнике настроения — '
    + 'так врач увидит динамику. Если бессонница держится больше двух недель, обязательно скажите об этом на приёме.',
  sadness: 'Спасибо, что поделились. То, что вы сейчас чувствуете, важно, и вы не обязаны справляться с этим в одиночку. '
    + 'Запишите своё состояние в дневник настроения — это поможет врачу точнее подобрать помощь. Если станет хуже, не откладывайте обращение к врачу.',
  greeting: 'Здравствуйте! Я простой вспомогательный бот-помощник, не врач. Можете рассказать, как вы себя сегодня чувствуете?',
  default: 'Я вас слышу. Расскажите немного подробнее — что сейчас больше всего беспокоит? '
    + 'Напомню: я не ставлю диагнозы, но могу поддержать и подсказать, когда стоит обратиться к врачу.',
};

function respond(text) {
  const intent = detectIntent(text || '');
  return { intent, reply: RESPONSES[intent] };
}

module.exports = { respond, detectIntent };
