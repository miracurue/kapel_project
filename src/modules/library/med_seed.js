function ensureMedArticles(db, P) {
  const exists = db.prepare('SELECT 1 FROM library_items WHERE slug=?');
  const t = P.iso(new Date());
  const todo = ITEMS.filter((i) => !exists.get(i.slug));
  if (!todo.length) return 0;
  db.transaction(() => {
    for (const item of todo) {
      const info = db
        .prepare(
          "INSERT INTO library_items(slug,media,status,current_version,tags_json,created_at,updated_at) VALUES (?, 'read','published',1,?,?,?)",
        )
        .run(item.slug, JSON.stringify(item.tags), t, t);
      db.prepare(
        "INSERT INTO library_versions(item_id,version,title,summary,body_md,author,source,review_date,is_stand_in,created_at) VALUES (?,1,?,?,?,'Пример · ждёт ревью','Пример для демонстрации, не клиническая рекомендация',?,1,?)",
      ).run(Number(info.lastInsertRowid), item.title, item.summary, item.body, t.slice(0, 10), t);
    }
    reindexFts(db);
  })();
  return todo.length;
}

module.exports = { ensureMedArticles, MED_ITEMS: ITEMS };
