function resolveAppendix(label) {
  if (typeof label !== 'string') return null;
  const normalized = label
    .trim()
    .replace(/^app:/i, '')
    .replace(/^Приложение\s+/i, '');
  const row = APPENDICES.find((entry) => entry.appendix === normalized);
  return row ? { ...row, codes: [...row.codes] } : null;
}

function policyForCode(code) {
  const row = APPENDICES.find((entry) => entry.codes.includes(code));
  if (row) return { ...row, codes: [...row.codes], code, href: `/work?tab=tools&tool=${code}` };
  // Методики других клинреков без реализации («Скоро появится»): не назначаются, не проходятся.
  return require('./clinrec_methods').soonPolicy(code);
}

function catalogMode(code) {
  return policyForCode(code)?.mode || null;
}

