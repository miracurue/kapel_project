function arrange(chapter) {
  const order = LAYOUT[chapter.key];
  if (!order || chapter.error) return chapter;
  const left = [...chapter.blocks];
  const take = (ref) => {
    let i = -1;
    if (ref.startsWith('#tiles')) {
      const n = Number(ref.slice(6));
      let seen = -1;
      i = left.findIndex((b) => b.type === 'tiles' && ++seen === n);
    } else i = left.findIndex((b) => b.title === ref);
    return i < 0 ? null : left.splice(i, 1)[0];
  };
  const placed = [];
  for (const entry of order) {
    const [ref, span] = Array.isArray(entry) ? entry : [entry];
    const b = take(ref);
    if (b) placed.push(span ? { ...b, span } : b);
  }
  chapter.blocks = [...placed, ...left];
  return chapter;
}

