const DENY = [
  // диагноз как утверждение
  {
    id: 'diagnosis',
    re: /(у\s+вас|у\s+тебя|вам\s+поставлен[ао]?|ваш\s+диагноз)[^.!?\n]{0,40}(депресси|тревожн\S*\s+расстройств|биполяр|шизофрен|птср|расстройств|невроз|психоз)/i,
  },
  { id: 'diagnosis2', re: /(вы\s+больны|вы\s+страдаете|это\s+(клиническая\s+)?депрессия|диагностирую)/i },
  // дозы и схемы приёма
  { id: 'dose', re: /\d+(?:[.,]\d+)?\s*(мг|mg|мкг|мл|таблет|капсул|капель|раз\s+в\s+день)/i },
  { id: 'dose2', re: /(принимайте|выпейте|примите|увеличьте\s+дозу|уменьшите\s+дозу|отмените|бросьте\s+принимать)/i },
  // названия лечения
  { id: 'drug', re: new RegExp(`(${DRUGS.join('|')})`, 'i') },
  // обещания
  { id: 'promise', re: /(гарантирую|обещаю|точно\s+пройдёт|всё\s+будет\s+хорошо|вылечу|обязательно\s+выздоровеете)/i },
];

/**
 * @param {string} text
 * @param {{skip?: string[]}} [opts] skip — исключения для справочных ответов специалисту о препарате
 *   и авторских статей (см. gateway.run); диагнозы, императивы и обещания остаются под запретом.
 * @returns {{ok: boolean, matched: string[]}}
 */
function check(text, { skip = [] } = {}) {
  const t = String(text || '');
  const matched = DENY.filter((d) => !skip.includes(d.id) && d.re.test(t)).map((d) => d.id);
  return { ok: matched.length === 0, matched };
}

module.exports = { check, DENY };
