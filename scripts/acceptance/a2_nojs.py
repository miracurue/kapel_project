"""A2 NFR-008: без JS — сообщение пациента, отметка приёма, сохранение черновика заключения, подпись, калькулятор, тёмная тема."""
from a2_common import *

NOJS = dict(viewport={'width': 390, 'height': 844}, java_script_enabled=False)
with sync_playwright() as p:
    b = launch(p)
    ctx = b.new_context(**NOJS)
    pg = ctx.new_page()
    pg.goto(BASE + '/login')
    pg.fill('input[name=email]', ACC['p1']); pg.fill('input[name=password]', PWD)
    pg.click('form[action="/login"] button[type=submit]'); pg.wait_for_load_state()
    log('nojs login ->', pg.url.replace(BASE, ''))
    go(pg, '/messages?with=2')
    pg.fill('textarea[name=body]', 'сообщение без JS')
    pg.click('form[action="/messages"] button[type=submit]'); pg.wait_for_load_state()
    log('nojs msg:', txt(pg, '[role=status],.flash', 120), '| sent visible:', 'сообщение без JS' in pg.inner_text('main'))
    go(pg, '/meds')
    pg.locator('form[action="/meds/log"] button[value=taken]').first.click(); pg.wait_for_load_state()
    log('nojs meds:', txt(pg, '[role=status],.flash', 120))
    go(pg, '/learn/tdr')
    pg.click('form[action$="/read"] button[type=submit]'); pg.wait_for_load_state()
    log('nojs learn read:', txt(pg, '[role=status],.flash', 100), '| print button visible w/o JS:', pg.locator('button:has-text("Печать")').is_visible() if pg.locator('button:has-text("Печать")').count() else 'absent')
    ctx.close()
    ctx = b.new_context(**NOJS)
    pg = ctx.new_page()
    pg.goto(BASE + '/login')
    pg.fill('input[name=email]', ACC['plg']); pg.fill('input[name=password]', PWD)
    pg.click('form[action="/login"] button[type=submit]'); pg.wait_for_load_state()
    go(pg, '/conclusions/2')
    pg.fill('textarea[name=findings]', 'Описание без JS')
    pg.click('form[action="/conclusions/2"] button[type=submit]'); pg.wait_for_load_state()
    log('nojs conclusion save:', txt(pg, '[role=status],.flash', 100), '| kept:', pg.input_value('textarea[name=findings]'))
    go(pg, '/patients/8/exam/1') if False else None
    go(pg, '/tools/calculator/phq9')
    names = pg.evaluate("[...new Set([...document.querySelectorAll('main form input[type=radio]')].map(r=>r.name))]")
    for nm in names:
        pg.locator('input[name="%s"][value="1"]' % nm).check()
    pg.click('main form button[type=submit]'); pg.wait_for_load_state()
    log('nojs calc:', txt(pg, 'main', 200)[100:200])
    ctx.close()
    # тёмная тема
    ctx = b.new_context(color_scheme='dark', viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
    pg = ctx.new_page()
    pg.goto(BASE + '/login')
    pg.fill('input[name=email]', ACC['plg']); pg.fill('input[name=password]', PWD)
    pg.click('form[action="/login"] button[type=submit]'); pg.wait_for_load_state()
    go(pg, '/conclusions/2')
    shot(pg, 'dark_conclusion_plg_mob', full=False)
    go(pg, '/tools/import')
    shot(pg, 'dark_import_plg_mob', full=False)
    ctx.close()
    b.close()
