"""A1 CLN-022/004/005/015/017/018: завершение наблюдения (Алексеева id 11, p7), отложить жёлтый флаг, теги, заметки (приватность от второго врача), материалы пациента из ИИ, журнал."""
from a0_common import *


def log(*a):
    print(*a, flush=True)


with sync_playwright() as p:
    b = launch(p)
    ctx, psy = login(b, 'psy1')
    psy.goto(BASE + '/patients')
    row = psy.locator('tr:has-text("Алексеева")')
    log('ARCHIVE forms in row:', row.locator('form').count(), '| button text', row.locator('button').all_inner_texts())
    row.locator('button:has-text("Завершить")').click()
    psy.wait_for_load_state()
    log('ARCHIVE ->', psy.url.replace(BASE, ''), psy.inner_text('main')[:300].replace('\n', ' | '))
    ctx.close()
    ctx, p7 = login(b, 'p7', MOB)
    p7.goto(BASE + '/dashboard')
    log('P7 after archive:', p7.inner_text('main')[:400].replace('\n', ' | '))
    shot(p7, 'cln_p7_after_archive_mob', full=False)
    ctx.close()
    ctx, psy = login(b, 'psy1')
    psy.goto(BASE + '/patients?view=archive')
    log('ARCHIVE list:', psy.inner_text('main')[:300].replace('\n', ' | '))
    link = psy.locator('tr:has-text("Алексеева") button:has-text("Вернуть"), tr:has-text("Алексеева") button:has-text("наблюдение")')
    log('restore buttons', link.count())
    if link.count():
        link.first.click()
        psy.wait_for_load_state()
        log('RESTORED ->', psy.inner_text('main')[:150].replace('\n', ' | '))
    # заметка
    psy.goto(BASE + '/patients/5/notes')
    psy.fill('textarea[name=body], textarea[name=text], textarea', 'ПРИВАТНАЯ-ЗАМЕТКА-ВРАЧА-1')
    psy.locator('form[action="/patients/5/notes"] button[type=submit]').click()
    psy.wait_for_load_state()
    log('NOTE saved:', 'ПРИВАТНАЯ-ЗАМЕТКА-ВРАЧА-1' in psy.inner_text('main'))
    # postpone yellow
    psy.goto(BASE + '/dashboard')
    pb = psy.locator('button:has-text("Отложить")')
    log('postpone buttons:', pb.count())
    if pb.count():
        pb.first.click()
        psy.wait_for_load_state()
        log('POSTPONE ->', psy.inner_text('main')[:200].replace('\n', ' | '))
    ctx.close()
    ctx, plg = login(b, 'plg')
    plg.goto(BASE + '/patients/5/notes')
    log('PSYCHOLOGIST sees psy1 private note:', 'ПРИВАТНАЯ-ЗАМЕТКА-ВРАЧА-1' in plg.inner_text('main'))
    ctx.close()
    # материалы пациента из ИИ: тред по пациенту + загрузка
    ctx, psy = login(b, 'psy1')
    r = psy.request.post(BASE + '/ai/new', form={'patient_id': '5'}, max_redirects=0)
    thread = r.headers.get('location')
    psy.goto(BASE + thread)
    psy.locator('#ws-attach summary').click()
    psy.set_input_files('#ws-files', '/tmp/a1files/vypiska.txt')
    psy.click('#ws-attach-form button[type=submit]')
    psy.wait_for_load_state()
    psy.click('button:has-text("Сохранить в диалог")')
    psy.wait_for_load_state()
    psy.goto(BASE + '/patients/5/materials')
    log('MATERIALS tab:', psy.inner_text('main')[-500:].replace('\n', ' | '))
    shot(psy, 'cln_materials_psy_desk', full=False)
    psy.goto(BASE + '/patients/5/journal')
    t = psy.inner_text('main')
    log('JOURNAL head:', t[300:900].replace('\n', ' | '))
    ctx.close()
    ctx, plg = login(b, 'plg')
    plg.goto(BASE + '/patients/5/materials')
    log('PLG materials of psy1 upload visible:', 'vypiska' in plg.inner_text('main'))
    ctx.close()
    b.close()
