from a2_common import *

with sync_playwright() as p:
    b = launch(p)
    ctx, d = login(b, 'psy1', DESK)
    go(d, '/patients/6/learn')
    d.click('form[action$="/previsit/request"] button[type=submit]')
    d.wait_for_load_state()
    log('REQUESTED:', txt(d, '[role=status],.flash', 200))
    d.locator('form[action$="/learn/assign"] button').first.click()
    d.wait_for_load_state()
    log('ASSIGN module:', txt(d, '[role=status],.flash', 200))
    ctx.close()
    ctx, pm = login(b, 'patient2.worsening@example.com', MOB)
    go(pm, '/dashboard')
    log('P2 DASH:', txt(pm, 'main', 800))
    shot(pm, 'previsit_dash_p2_mob')
    go(pm, '/previsit')
    log('P2 PREVISIT:', txt(pm, 'main', 2500), 'ovf', overflow(pm))
    shot(pm, 'previsit_form_p2_mob')
    # заполнить: числа, свободные тексты; в одном — кризисная фраза
    radios = pm.locator('input[type=radio]')
    names = pm.evaluate("[...new Set([...document.querySelectorAll('input[type=radio]')].map(r=>r.name))]")
    log('radio groups', names)
    for n in names[:2]:
        pm.locator('input[name=%s]' % n).nth(3).check()
    tas = pm.locator('textarea')
    log('textareas', tas.count())
    tas.first.fill('Последние дни хуже сплю. Иногда думаю, что лучше бы меня не было, хочу умереть.')
    pm.click('button[value=send]')
    pm.wait_for_load_state()
    log('SENT previsit:', txt(pm, 'main', 900))
    shot(pm, 'previsit_sent_crisis_p2_mob')
    # обучение: модуль
    go(pm, '/learn')
    log('P2 LEARN:', txt(pm, 'main', 700))
    pm.locator('main a[href^="/learn/"]').first.click()
    pm.wait_for_load_state()
    log('MODULE:', pm.url.replace(BASE, ''), txt(pm, 'main', 1800), 'ovf', overflow(pm))
    shot(pm, 'learn_module_p2_mob')
    log('module forms', pm.evaluate("[...document.forms].map(f=>f.getAttribute('action'))"), 'print btn', pm.locator('button:has-text("Печать")').count())
    pm.click('form[action$="/read"] button[type=submit]')
    pm.wait_for_load_state()
    log('READ:', txt(pm, '[role=status],.flash', 150))
    ctx.close()
    ctx, d = login(b, 'psy1', DESK)
    go(d, '/patients/6/visit')
    t = d.inner_text('main')
    i = t.find('Перед приёмом от пациента')
    log('DOC VISIT previsit:', t[i:i + 700].replace('\n', ' | '))
    shot(d, 'previsit_visit_doc_desk')
    go(d, '/crisis')
    log('CRISIS has previsit item:', 'нкет' in d.inner_text('main'), txt(d, 'main', 1800)[330:1100])
    b.close()
